#!/usr/bin/env python3
"""
Regenerate <variant>/Dockerfile.sonicsort from upstream's generated
<variant>/Dockerfile (default variant: 3.14/slim-trixie).

    python sonicsort/generate.py [3.14/slim-trixie]

Re-run after pulling an upstream docker-library/python update (e.g. a new
PYTHON_VERSION) so SonicSort's build follows it.

The one change from upstream: the hardcoded `FROM debian:<suite>-slim` becomes
`FROM ${DEBIAN_BASE}`, defaulting to that same public image. SonicSort passes
DEBIAN_BASE=sonicsort-debian:local -- its own Debian slim rootfs, built from
poslogica/debuerreotype -- so CPython is compiled on (and ships on) a base we
built ourselves. Everything else (PYTHON_VERSION, configure flags, PGO/LTO)
is upstream's.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
#
# GENERATED by sonicsort/generate.py from ./Dockerfile -- do not edit;
# change the generator and re-run it instead.
#
# SonicSort build: upstream's Dockerfile with the Debian base made overridable
# (DEBIAN_BASE), so it builds on sonicsort-debian:local from poslogica/debuerreotype.
#
"""


def generate(variant: str) -> Path:
    """Write <variant>/Dockerfile.sonicsort; returns its path."""
    src = ROOT / variant / "Dockerfile"
    text = src.read_text(encoding="utf-8")

    match = re.search(r"^FROM (debian:\S+)$", text, re.M)
    if not match:
        sys.exit(f"{src}: no 'FROM debian:...' line -- only Debian variants are supported")
    public_base = match.group(1)

    # Upstream's "generated, do not edit" banner, replaced by ours.
    text = re.sub(r"\A(#.*\n)+\n", "", text)
    text = text.replace(
        f"FROM {public_base}\n",
        f"ARG DEBIAN_BASE={public_base}\nFROM ${{DEBIAN_BASE}}\n",
        1,
    )

    out = src.with_name("Dockerfile.sonicsort")
    out.write_text(HEADER + "\n" + text, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    print(generate(sys.argv[1] if len(sys.argv) > 1 else "3.14/slim-trixie"))
